/**
 * Prebuild script: reads content/blog/*.md, generates:
 *   - frontend/src/data/blogManifest.js  (metadata for index page)
 *   - frontend/public/blog/*.md          (served statically for BlogPost)
 *   - frontend/public/sitemap-blog.xml   (SEO)
 */
import { readdir, readFile, writeFile, copyFile, mkdir } from "fs/promises";
import { existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dir, "../..");
const SRC_DIR = join(ROOT, "content/blog");
const OUT_DIR = join(__dir, "../public/blog");
const MANIFEST_OUT = join(__dir, "../src/data/blogManifest.js");
const SITEMAP_OUT = join(__dir, "../public/sitemap-blog.xml");
const BASE_URL = "https://vinoinvest-platform.vercel.app";
const TODAY = new Date().toISOString().slice(0, 10);

// Category → audience mapping
const B2B_CATS = new Set(["Fiscalità", "En Primeur", "Uscita"]);
const B2C_CATS = new Set(["Principianti"]);

function audience(category) {
  if (B2B_CATS.has(category)) return "b2b";
  if (B2C_CATS.has(category)) return "b2c";
  return "both";
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const block = match[1];
  const out = {};

  // title: "..."
  const title = block.match(/^title:\s*"([^"]+)"/m);
  if (title) out.title = title[1];

  // slug: "..."
  const slug = block.match(/^slug:\s*"([^"]+)"/m);
  if (slug) out.slug = slug[1];

  // meta_description: "..."
  const desc = block.match(/^meta_description:\s*"([^"]+)"/m);
  if (desc) out.meta_description = desc[1];

  // category: "..."
  const cat = block.match(/^category:\s*"([^"]+)"/m);
  if (cat) out.category = cat[1];

  // reading_time: "..."
  const rt = block.match(/^reading_time:\s*"([^"]+)"/m);
  if (rt) out.reading_time = rt[1];

  // keywords: ["...", "..."]
  const kw = block.match(/^keywords:\s*\[([^\]]+)\]/m);
  if (kw) {
    out.keywords = kw[1]
      .split(",")
      .map(k => k.trim().replace(/^"|"$/g, "").replace(/^'|'$/g, ""))
      .filter(Boolean);
  } else {
    out.keywords = [];
  }

  return out;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  const files = (await readdir(SRC_DIR)).filter(f => f.endsWith(".md")).sort();
  const manifest = [];

  for (const file of files) {
    const srcPath = join(SRC_DIR, file);
    const raw = await readFile(srcPath, "utf8");
    const meta = parseFrontmatter(raw);

    // Derive slug from filename if not in frontmatter
    const slug = meta.slug || file.replace(/\.md$/, "");

    // Copy .md to public/blog/
    await copyFile(srcPath, join(OUT_DIR, `${slug}.md`));

    manifest.push({
      slug,
      title: meta.title || slug,
      meta_description: meta.meta_description || "",
      category: meta.category || "Analisi",
      reading_time: meta.reading_time || "5 min",
      keywords: meta.keywords || [],
      audience: audience(meta.category || ""),
    });
  }

  // Sort by category then title
  manifest.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

  // Write manifest JS module
  const jsContent = `// AUTO-GENERATED by scripts/gen-blog-data.mjs — do not edit manually
export const BLOG_MANIFEST = ${JSON.stringify(manifest, null, 2)};

export const BLOG_CATEGORIES = [
  ...new Set(BLOG_MANIFEST.map(p => p.category))
].sort();
`;
  await writeFile(MANIFEST_OUT, jsContent, "utf8");

  // Write sitemap
  const urls = manifest.map(
    p => `  <url>
    <loc>${BASE_URL}/blog/${p.slug}</loc>
    <lastmod>${TODAY}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
  </url>`
  );
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/9/0.1">
${urls.join("\n")}
</urlset>
`;
  await writeFile(SITEMAP_OUT, sitemap, "utf8");

  console.log(`[gen-blog-data] ${manifest.length} articles → manifest + ${files.length} .md files → public/blog/`);
}

main().catch(e => { console.error(e); process.exit(1); });
